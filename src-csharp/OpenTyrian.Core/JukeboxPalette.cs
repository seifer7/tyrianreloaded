    private static readonly PaletteColor[] Palette = Load();

    public static ReadOnlyMemory<PaletteColor> Colors => Palette;

    private static PaletteColor[] Load()
    {
        var rgb = Convert.FromHexString(PaletteData);
        if (rgb.Length != PaletteSystem.ColorCount * 3)
            throw new InvalidDataException("The native jukebox palette must contain 256 RGB colors.");

        var colors = new PaletteColor[PaletteSystem.ColorCount];
        for (var i = 0; i < colors.Length; i++)
            colors[i] = new PaletteColor(rgb[i * 3], rgb[i * 3 + 1], rgb[i * 3 + 2]);
        return colors;
    }
